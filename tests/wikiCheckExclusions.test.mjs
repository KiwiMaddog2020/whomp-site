import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, mkdtempSync, readdirSync, readFileSync, symlinkSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import test from 'node:test';

// wiki-check must honour a policy's excludedIds (unfielded / pending-concept):
// the generator still lists those cards, but they have no canonical visual.
const site = resolve(import.meta.dirname, '..');
const game = resolve(process.env.WHOMP_REPO || '../whomp');
const available = ['game-data.json', 'tier-rankings.json', 'wiki-visuals.json']
  .every((name) => existsSync(join(game, 'data', name)));
const run = (args) => spawnSync(process.execPath, args, { cwd: site, encoding: 'utf8', maxBuffer: 1 << 26 });

let out = null;
let skip = available ? false : 'canonical game artifacts unavailable; set WHOMP_REPO';
if (!skip && process.env.WIKI_OUTDIR) {
  out = resolve(process.env.WIKI_OUTDIR); // a wiki already generated by the caller
} else if (!skip) {
  out = mkdtempSync(join(tmpdir(), 'wiki-out-'));
  const gen = run(['bin/generate.mjs', '--repo', game, '--outdir', out]);
  // Generation re-renders the visual gallery in an isolated Chrome; without one
  // there is no generated wiki to check, which is not this test's failure.
  if (gen.status !== 0) skip = `generate.mjs could not finish here: ${(gen.stderr.match(/Error: .*/) || ['unknown'])[0]}`;
}

/** A repo view whose wiki-visuals.json is edited by `mutate`; everything else is linked. */
const repoWith = (mutate) => {
  const root = mkdtempSync(join(tmpdir(), 'wiki-repo-'));
  mkdirSync(join(root, 'data'));
  for (const name of readdirSync(game)) if (name !== 'data' && name !== '.git') symlinkSync(join(game, name), join(root, name));
  for (const name of readdirSync(join(game, 'data'))) if (name !== 'wiki-visuals.json') symlinkSync(join(game, 'data', name), join(root, 'data', name));
  const V = JSON.parse(readFileSync(join(game, 'data/wiki-visuals.json'), 'utf8'));
  mutate(V);
  writeFileSync(join(root, 'data/wiki-visuals.json'), JSON.stringify(V));
  return root;
};
const check = (repo) => run(['bin/wiki-check.mjs', '--repo', repo, '--outdir', out]);
const message = (result) => `${result.stdout}${result.stderr}`;

test('wiki-check passes with excluded ids (riftHeart) carrying no visual', { skip, timeout: 600000 }, () => {
  const result = check(game);
  assert.equal(result.status, 0, message(result));
  assert.ok(readFileSync(join(out, 'wiki-bestiary.html'), 'utf8').includes('id="e-riftHeart"'));
});

test('an entry with no visual that is NOT excluded still fails', { skip, timeout: 600000 }, () => {
  // Drop blob's canonical visual while leaving its policy and page alone. The
  // model-level manifest guard refuses it before wiki-check's own requirement.
  const repo = repoWith((V) => { V.entries = V.entries.filter((entry) => entry.assetKey !== 'enemies:blob'); });
  const result = check(repo);
  assert.notEqual(result.status, 0);
  assert.match(message(result), /Wiki visual contract failed[\s\S]*visual entry coverage/);
});
